using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Windows;
using System.Windows.Controls;
using Microsoft.Win32;
using GymManagementSystem.Data.Repositories;
using GymManagementSystem.Models;
using GymManagementSystem.Services;

namespace GymManagementSystem.Views
{
    public partial class ReportsView : UserControl
    {
        private readonly ReportService _reportService = new();
        private readonly AttendanceRepository _attRepo = new();

        public ReportsView()
        {
            InitializeComponent();
            Loaded += (s, e) =>
            {
                DpStartDate.SelectedDate = DateTime.Today.AddMonths(-1);
                DpEndDate.SelectedDate = DateTime.Today;
                GenerateReports();
            };
        }

        private void BtnGenerate_Click(object sender, RoutedEventArgs e)
        {
            GenerateReports();
        }

        public void GenerateReports()
        {
            if (DgMembershipReport == null || TxtTotalPaid == null) return;

            var start = DpStartDate?.SelectedDate ?? DateTime.Today.AddMonths(-1);
            var end = DpEndDate?.SelectedDate ?? DateTime.Today;

            // 1. Membership Status Report
            var memReport = _reportService.GetMembershipStatusReport();
            DgMembershipReport.ItemsSource = memReport;

            // 2. Financial Summary
            var financial = _reportService.GetFinancialReport(start, end);
            TxtTotalPaid.Text = $"${financial.TotalPaid:N2}";
            TxtTotalPending.Text = $"${financial.TotalPending:N2}";
            TxtTotalOverdue.Text = $"${financial.TotalOverdue:N2}";

            if (financial.ByPaymentMethod.Count > 0)
            {
                var sb = new StringBuilder();
                foreach (var kvp in financial.ByPaymentMethod)
                {
                    sb.AppendLine($"• {kvp.Key}: ${kvp.Value:N2}");
                }
                TxtPaymentBreakdown.Text = sb.ToString().TrimEnd();
            }
            else
            {
                TxtPaymentBreakdown.Text = "No paid transactions in this date range.";
            }

            // 3. Attendance Logs
            var attLogs = _attRepo.SearchAttendance(null, null)
                .Where(a => a.AttendanceDate >= start && a.AttendanceDate <= end)
                .ToList();

            DgRecentAttendance.ItemsSource = attLogs;
            var uniqueMembers = attLogs.Select(a => a.MemberId).Distinct().Count();
            TxtAttendanceStats.Text = $"Total {attLogs.Count} visit(s) recorded by {uniqueMembers} distinct member(s) between {start:yyyy-MM-dd} and {end:yyyy-MM-dd}.";
        }

        private void BtnExportReport_Click(object sender, RoutedEventArgs e)
        {
            var start = DpStartDate.SelectedDate ?? DateTime.Today.AddMonths(-1);
            var end = DpEndDate.SelectedDate ?? DateTime.Today;

            var memReport = _reportService.GetMembershipStatusReport();
            var financial = _reportService.GetFinancialReport(start, end);
            var attLogs = _attRepo.SearchAttendance(null, null)
                .Where(a => a.AttendanceDate >= start && a.AttendanceDate <= end)
                .ToList();

            var sb = new StringBuilder();
            sb.AppendLine("==========================================================");
            sb.AppendLine("          TITAN FITNESS - GYM MANAGEMENT SYSTEM           ");
            sb.AppendLine("                 OPERATIONS & FINANCIAL REPORT            ");
            sb.AppendLine("==========================================================");
            sb.AppendLine($"Generated Date : {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine($"Reporting Range: {start:yyyy-MM-dd} to {end:yyyy-MM-dd}");
            sb.AppendLine($"Generated By   : {AuthService.CurrentStaff?.FullName ?? "System Staff"}");
            sb.AppendLine("----------------------------------------------------------\n");

            sb.AppendLine("1. MEMBERSHIP STATUS BREAKDOWN:");
            foreach (var item in memReport)
            {
                sb.AppendLine($"   - {item.Category,-28}: {item.Count,4} ({item.Percentage}%)");
            }
            sb.AppendLine();

            sb.AppendLine("2. FINANCIAL COLLECTIONS SUMMARY:");
            sb.AppendLine($"   - Total Paid / Collected   : ${financial.TotalPaid:N2}");
            sb.AppendLine($"   - Pending Payments         : ${financial.TotalPending:N2}");
            sb.AppendLine($"   - Overdue Receivables      : ${financial.TotalOverdue:N2}");
            sb.AppendLine($"   - Total Transactions       : {financial.TransactionCount}");
            sb.AppendLine("   Collections by Payment Method:");
            foreach (var kvp in financial.ByPaymentMethod)
            {
                sb.AppendLine($"     • {kvp.Key,-18}: ${kvp.Value:N2}");
            }
            sb.AppendLine();

            sb.AppendLine("3. ATTENDANCE & GYM UTILIZATION:");
            sb.AppendLine($"   - Total Check-ins Recorded : {attLogs.Count}");
            sb.AppendLine($"   - Unique Members Visited   : {attLogs.Select(a => a.MemberId).Distinct().Count()}");
            sb.AppendLine("==========================================================");

            var saveDialog = new SaveFileDialog
            {
                Filter = "Text Document (*.txt)|*.txt",
                FileName = $"GymReport_{DateTime.Today:yyyyMMdd}.txt"
            };

            if (saveDialog.ShowDialog() == true)
            {
                File.WriteAllText(saveDialog.FileName, sb.ToString());
                MessageBox.Show("Summary report successfully exported!", "Export Complete", MessageBoxButton.OK, MessageBoxImage.Information);
            }
        }
    }
}
